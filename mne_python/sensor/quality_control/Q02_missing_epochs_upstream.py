# -*- coding: utf-8 -*-
"""Q02: Trace missing 7min50 epochs back to the inputs of 01_epoching.py.

Read-only QC. Processes IDs from subjects_lost_after_S01_psd_lateralisation.csv.
Checks inclusion in demographics_goodPreproc_subjects.csv, source FIF
availability/readability, raw duration, and whether the ORIGINAL event/epoch
settings of 01_epoching.py yield valid epochs. Does not save epochs or modify
subject lists.

Run:
 python mne_python/sensor/quality_control/Q02_missing_epochs_upstream.py --platform mac
 python mne_python/sensor/quality_control/Q02_missing_epochs_upstream.py --platform bluebear

Use --quinna-root and --epochs-root to override mounted paths if needed.
"""
import argparse
import logging
import os
import os.path as op
import traceback

import mne
import numpy as np
import pandas as pd


def roots(platform):
    if platform == "mac":
        return "/Volumes/quinna-camcan-1", "/Volumes/jenseno-sub2ctx/camcan"
    if platform == "bluebear":
        return "/rds/projects/q/quinna-camcan", "/rds/projects/j/jenseno-sub2ctx/camcan"
    raise ValueError(platform)


def load_ids(path):
    df = pd.read_csv(path, dtype=str)
    cols = [c for c in df if c.strip().lower().replace("_", "") in ("subjectid", "subid", "subject")]
    if not cols:
        cols = [c for c in df if not c.lower().startswith("unnamed")]
    if len(cols) != 1:
        raise ValueError(f"Cannot identify subject ID column: {list(df.columns)}")
    return df[cols[0]].dropna().astype(str).str.strip().str.replace(
        r"\\.0$", "", regex=True
    ).drop_duplicates().tolist()


def read_good_ids(path):
    df = pd.read_csv(path, dtype=str)
    if "Unnamed: 0" in df.columns:
        col = "Unnamed: 0"  # used as index in 01_epoching.py
    else:
        matches = [c for c in df if c.lower().replace("_", "") in ("subjectid", "subid")]
        if not matches:
            raise ValueError(f"No subject ID column in {path}")
        col = matches[0]
    return set(df[col].dropna().astype(str).str.strip().str.replace(
        r"\\.0$", "", regex=True
    ))


def inspect_one(sid, good_ids, preproc_dir, epoch_dirs, check_epoching=True):
    base = f"mf2pt2_sub-CC{sid}_ses-rest_task-rest_megtransdef"
    source = op.join(preproc_dir, base, base + "_preproc_raw.fif")
    epo_name = f"sub-CC{sid}_ses-rest_task-rest_megtransdef_epo.fif"
    output = {
        "SubjectID": sid,
        "in_good_preproc_list": sid in good_ids,
        "preproc_fif_exists": op.isfile(source),
        "preproc_fif": source,
        "epoch_in_original_quinna_dir": op.isfile(op.join(epoch_dirs[0], epo_name)),
        "epoch_in_S01_sub2ctx_dir": op.isfile(op.join(epoch_dirs[1], epo_name)),
        "status": "",
        "failure_stage": "",
        "error_type": "",
        "error_message": "",
        "sfreq": np.nan,
        "duration_s": np.nan,
        "n_events_original": np.nan,
        "n_epochs_original": np.nan,
        "n_times_original": np.nan,
    }
    if output["epoch_in_original_quinna_dir"] or output["epoch_in_S01_sub2ctx_dir"]:
        output["status"] = "EPOCH_EXISTS_SOMEWHERE"
        return output, ""
    if sid not in good_ids:
        output["status"] = "NOT_IN_EPOCHING_INPUT_LIST"
        return output, ""
    if not op.isfile(source):
        output["status"] = "PREPROC_FIF_MISSING"
        return output, ""

    stage = "read_preprocessed_fif"
    try:
        raw = mne.io.read_raw_fif(source, preload=False, verbose="ERROR")
        sfreq = float(raw.info["sfreq"])
        duration = raw.n_times / sfreq
        output["sfreq"] = sfreq
        output["duration_s"] = duration
        if not check_epoching:
            output["status"] = "PREPROC_READABLE_NOT_EPOCH_TESTED"
            return output, ""

        # Reproduce original 01_epoching.py settings without saving anything.
        stage = "make_fixed_length_events"
        events = mne.make_fixed_length_events(
            raw, id=1, start=5, stop=475,
            duration=470, first_samp=True, overlap=0.0
        )
        output["n_events_original"] = len(events)
        if len(events) == 0:
            raise ValueError("No events generated by original parameters")

        stage = "construct_original_epochs"
        epochs = mne.Epochs(
            raw, events, tmin=5, tmax=475,
            baseline=None, proj=True, picks="all", detrend=1,
            event_repeated="drop", reject=None,
            reject_by_annotation=False, preload=False, verbose="ERROR"
        )
        output["n_epochs_original"] = len(epochs)
        output["n_times_original"] = len(epochs.times)
        if len(epochs) == 0:
            raise ValueError("Original epoching produced zero usable epochs")
        output["status"] = "ORIGINAL_EPOCHING_CONSTRUCTS"
        return output, ""
    except Exception as exc:
        output["status"] = "EPOCHING_CHECK_FAILED"
        output["failure_stage"] = stage
        output["error_type"] = type(exc).__name__
        output["error_message"] = str(exc)
        return output, traceback.format_exc()


def main(args):
    quinna_default, sub2ctx_default = roots(args.platform)
    quinna = args.quinna_root or quinna_default
    sub2ctx = args.epochs_root or sub2ctx_default
    info_dir = op.join(quinna, "dataman", "data_information")
    lost_csv = op.join(info_dir, "subjects_lost_after_S01_psd_lateralisation.csv")
    good_csv = op.join(info_dir, "demographics_goodPreproc_subjects.csv")
    preproc_dir = op.join(quinna, "camcan_bigglm", "processed-data", "CamCAN_firstlevel")
    epoch_dirs = (
        op.join(quinna, "derivatives", "meg", "sensor", "epoched-7min50"),
        op.join(sub2ctx, "derivatives", "meg", "sensor", "epoched-7min50"),
    )
    out_dir = args.output_dir or op.join(sub2ctx, "derivatives", "meg", "sensor",
                                        "quality_control", "Q02_missing_epochs_upstream")
    for path in (info_dir, preproc_dir):
        if not op.isdir(path):
            raise NotADirectoryError(
                f"Directory unavailable: {path}. Check SMB mount or override --quinna-root."
            )
    for path in (lost_csv, good_csv):
        if not op.isfile(path):
            raise FileNotFoundError(f"Required CSV unavailable: {path}")
    if not any(op.isdir(d) for d in epoch_dirs):
        raise NotADirectoryError(f"Neither epochs directory is accessible: {epoch_dirs}")

    os.makedirs(out_dir, exist_ok=True)
    logging.basicConfig(filename=op.join(out_dir, "Q02_tracebacks.log"),
                        filemode="w", level=logging.INFO, force=True)
    ids = load_ids(lost_csv)
    good_ids = read_good_ids(good_csv)
    print(f"Checking {len(ids)} lost subjects. Source: {preproc_dir}")
    print(f"Epoch locations: {epoch_dirs}")
    results = []
    for n, sid in enumerate(ids, 1):
        result, tb = inspect_one(sid, good_ids, preproc_dir, epoch_dirs,
                                 check_epoching=not args.paths_only)
        results.append(result)
        print(f"[{n}/{len(ids)}] {sid}: {result['status']} "
              f"{result['failure_stage']} {result['error_message']}", flush=True)
        if tb:
            logging.error("Subject %s:\n%s", sid, tb)

    df = pd.DataFrame(results)
    output_csv = op.join(out_dir, "Q02_upstream_epoch_qc.csv")
    df.to_csv(output_csv, index=False)
    print("\n", df["status"].value_counts().to_string())
    print(f"Saved: {output_csv}")
    print("Note: ORIGINAL_EPOCHING_CONSTRUCTS is a diagnostic, not proof that saving "
          "or preloading the full epoch would succeed.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--platform", choices=("mac", "bluebear"), default="mac")
    parser.add_argument("--quinna-root", default=None)
    parser.add_argument("--epochs-root", default=None,
                        help="Root of sub2ctx/camcan (not the epochs directory itself)")
    parser.add_argument("--output-dir", default=None)
    parser.add_argument("--paths-only", action="store_true",
                        help="Check paths and raw readability; skip original epoch construction")
    main(parser.parse_args())
